// Package jsoncodec 是 rx 之上的 JSON 请求(返回)数据编解码器：请求绑定、业务错误响应与统一响应输出。
//
// 业务 Handler 只需要写"拿到入参、调用用例、返回数据或错误"，
// 其余都交给这里的 Handler。
//
// 这里是业务接口通用的编解码方式，业务接口统一用它。
// 请求绑定、响应结构、错误编码是绑在一起的一套，要对接第三方、报文格式不同时，
// 就在 jsoncodec 之外另建一套，不要改这里：
// 这里被所有业务接口共用，改了会影响全部接口。
//
// 第三方接口的错误要在自己的 handler 里直接输出，不要用 AbortWithError：
// 那个错误会落到引擎的 ErrorEncoder，响应格式还是这里的统一格式。
// 也不要在 ErrorEncoder 里按错误类型分支判断，通用层不该知道第三方接口的存在。
